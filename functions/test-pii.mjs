let fail = 0;
for (const [src, bad] of LEAK) {
  const { text } = maskPII(src);
  const leaked = bad.filter((b) => text.includes(b));
  if (leaked.length || !text.includes(MASK)) { fail++; console.log(`❌ LEAK  «${src}» → «${text}»  새는 것: ${leaked.join(",") || "(가림 없음)"}`); }
}
let over = 0;
for (const src of KEEP) {
  const { text } = maskPII(src);
  if (text !== src) { over++; console.log(`⚠️ OVER  «${src}» → «${text}»`); }
}
// 학생이 직접 고른 낱말
// «지우» 이름 때문에 «지우개»가 가려지면 안 된다
const jw = maskPII("동생 지우랑 놀았다. 지우가 지우개를 빌려줬다.").text;
if (!jw.includes("지우개") || jw.includes("지우가")) { fail++; console.log(`❌ 경계 «${jw}»`); }
// maskWords 폭주 방지: 40개·20자 상한, ㅇㅇㅇ 포함 낱말 무시
const big = maskPII("가".repeat(5000), { extraWords: Array.from({ length: 500 }, (_, i) => "가".repeat((i % 30) + 1)) });
if (big.text.length > 5000) { fail++; console.log("❌ 상한"); }
const ex = maskPII("우리 반 똘이는 착하다. 똘이가 웃었다.", { extraWords: ["똘이"] });
if (ex.text.includes("똘이")) { fail++; console.log(`❌ extraWords «${ex.text}»`); }
// 다른 AI(Llama)가 쓴 가짜 일기·편지 3묶음(test-data) — 학년·반·선생님·도시 이름은 개인정보가 아니다
import { readFileSync, readdirSync } from "fs";
const NOT_PII = /^(선생님|\d학년|\d반|전주|서울|부산)$/;
for (const f of readdirSync(new URL("./test-data/", import.meta.url)).filter((x) => x.startsWith("pii-"))) {
  for (const { text, pii } of JSON.parse(readFileSync(new URL(`./test-data/${f}`, import.meta.url), "utf8"))) {
    const out = maskPII(text).text;
    for (const p of pii) {
      const core = p.trim().split(/\s+/).pop().replace(/(이|아파트|초등학교)$/, "") || p.trim();
      if (NOT_PII.test(core)) continue;
      if (out.includes(core)) { fail++; console.log(`❌ ${f} LEAK [${core}] ${out}`); }
    }
    if (!pii.length && out !== text) { over++; console.log(`⚠️ ${f} OVER ${out}`); }
  }
}
console.log(`LEAK ${LEAK.length - fail}/${LEAK.length} 막음 · KEEP ${KEEP.length - over}/${KEEP.length} 그대로`);
process.exit(fail || over ? 1 : 0);
