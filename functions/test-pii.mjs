let fail = 0;
for (const [src, bad] of LEAK) {
  const { text } = maskPII(src);
  const leaked = bad.filter((b) => text.includes(b));
  if (leaked.length || !text.includes(MASK)) { fail++; console.log(`❌ LEAK  «${src}» → «${text}»  새는 것: ${leaked.join(",") || "(가림 없음)"}`); }
}
let over = 0;
for (const src of KEEP) {
  const { text } = maskPII(src);
  if (text !== src) { over++; console.log(`⚠️ OVER  «${src}» → «${text}»`); }
}
