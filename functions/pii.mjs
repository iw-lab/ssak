  // 긴 숫자(계좌·카드·하이픈 없는 번호) — 숫자 9개 이상이 붙거나 -·공백·점으로 이어지면(쉼표 금액 «1,000,000원»은 제외)
  sub(/(?<![\d,])(?:\d[-.\s]?){8,}\d(?![\d,])/g, "number", (m) => (/^\d{4}[.\s-]\d{1,2}[.\s-]\d{1,2}$/.test(m) ? m : MASK));
